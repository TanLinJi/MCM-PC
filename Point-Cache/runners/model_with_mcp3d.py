# Section 6: Memory Cell (single cell of the 2x3 matrix)
# ----------------------------------------------------------------------------
# Per plan section 3.5 (system) and audit gaps C1-C2.
# A cell stores per-class lists of items. Item structure depends on cell type:
#   - confidence cells:  [feature_or_patch, loss]
#   - compactness cells: [feature_or_patch, loss, raw_pc, geom_score]
#   - boundary cells:    [feature_or_patch, loss, prob_map]
# ============================================================================
@dataclass
class CellConfig:
    """Configuration for a single memory cell.

    Attributes:
        name:           identifier such as 'global_conf', 'local_comp'
        representation: 'global' (whole-cloud feature) or 'local' (patch features)
        function:       'conf' | 'comp' | 'bnd'
        shot_capacity:  K shots per class
        alpha:          logit weight when fusing (Tip-Adapter style)
        beta:           sharpness in (-beta + beta * affinity).exp()
        enabled:        toggle for ablation A1 (leave-one-out)
    """
    name: str
    representation: str       # 'global' or 'local'
    function: str             # 'conf' | 'comp' | 'bnd'
    shot_capacity: int = 3
    alpha: float = 4.0
    beta: float = 3.0
    enabled: bool = True


class MemoryCell:
    """Generic memory cell that stores per-class items with a maximum shot capacity.

    Replacement update strategy:
      - confidence cells:    by lowest entropy/loss
      - compactness cells:   by smallest geometric score (after z-score normalize + omega-fuse)
      - boundary cells:      by lowest entropy within mid-entropy band
    """

    def __init__(self, config: CellConfig):
        self.cfg = config
        self.cache: Dict[int, List[list]] = {}

    def _sort_key(self, item: list) -> float:
        """Sort key for item replacement. Smaller is better (kept first)."""
        # item layout: [feat, ... , score]
        # for confidence/boundary -> score = loss (last numeric)
        # for compactness -> score = geom_combined_score (provided externally)
        if self.cfg.function == "comp":
            return item[-1]  # geom_combined_score
        return item[-2] if len(item) >= 3 else item[-1]

    def update(self, pred: int, item: list) -> None:
        """Update cell with a new item, keeping at most `shot_capacity` items per class."""
        if not self.cfg.enabled:
            return

        if pred in self.cache:
            if len(self.cache[pred]) < self.cfg.shot_capacity:
                self.cache[pred].append(item)
            else:
                # replace worst (last after sort) if new item is better
                worst_idx = -1
                if self._sort_key(item) < self._sort_key(self.cache[pred][worst_idx]):
                    self.cache[pred][worst_idx] = item
            self.cache[pred].sort(key=self._sort_key)
        else:
            self.cache[pred] = [item]

    def is_filled(self, num_classes: int) -> bool:
        """Whether all classes have reached shot_capacity."""
        if len(self.cache) < num_classes:
            return False
        return all(len(v) >= self.cfg.shot_capacity for v in self.cache.values())

    def num_items(self) -> int:
        return sum(len(v) for v in self.cache.values())


