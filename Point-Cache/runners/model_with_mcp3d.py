@dataclass
class FusionWeights:
    """Adaptive fusion weights for multi-source logits.

    zeta_text: weight on text-anchor logits (zero-shot)
    zeta_cell: per-cell additive weights, alpha_i in plan
    zeta_residual: weight on residual refinement (default 0.3 per Gap E3)
    enable_residual: toggle for MCP-3D++ extension (default OFF for AAAI)
    """
    zeta_text: float = 1.0
    zeta_cell: Dict[str, float] = field(default_factory=dict)
    zeta_residual: float = 0.3
    enable_residual: bool = False


@torch.no_grad()
def fuse_multi_source_logits(
    text_logits: torch.Tensor,            # (1, n_cls)
    cell_logits_dict: Dict[str, torch.Tensor],  # name -> (1, n_cls)
    weights: FusionWeights,
    residual_logits: Optional[torch.Tensor] = None,
) -> torch.Tensor:
    """Combine text logits with all enabled cell logits.

    Final logits = zeta_text * text + sum_i zeta_cell[i] * cell_logits[i]
                   + zeta_residual * residual (if enable_residual)

    Notes:
      - boundary cells contribute negatively (cf. Point-Cache neg cache).
      - residual is OFF for AAAI version; CVPR may turn it on per A5 result.
    """
    final = weights.zeta_text * text_logits
    for name, cl in cell_logits_dict.items():
        if cl is None:
            continue
        sign = -1.0 if name.endswith("_bnd") else 1.0
        w = weights.zeta_cell.get(name, 1.0)
        final = final + sign * w * cl

    if weights.enable_residual and residual_logits is not None:
        final = final + weights.zeta_residual * residual_logits

    return final


