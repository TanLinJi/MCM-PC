def main():
    args = get_arguments()
    set_random_seed(args.seed)

    # MCP-3D specific args (TODO W3: move to utils.get_arguments())
    if not hasattr(args, "omega"):
        args.omega = DEFAULT_OMEGA
    if not hasattr(args, "kappa0"):
        args.kappa0 = DEFAULT_KAPPA0
    if not hasattr(args, "use_vmf"):
        args.use_vmf = True
    if not hasattr(args, "paraphrase_json"):
        args.paraphrase_json = ""  # path to deepseek paraphrase JSON
    if not hasattr(args, "enable_residual"):
        args.enable_residual = False  # MCP-3D++ extension, OFF for AAAI

    config_path = args.config
    clip_model, lm3d_model = load_models(args)
    preprocess = None

    dataset_name = args.dataset
    print(f"Processing {dataset_name} dataset with MCP-3D.")
    cfg = get_config_file(args, config_path, dataset_name)
    print("\nDataset config:")
    print(cfg, "\n")

    test_loader, classnames, template = build_test_data_loader(args, dataset_name, args.data_root, preprocess)
    num_classes = len(classnames)

    # ----- text anchors: vMF MAP if paraphrases available, else fall back to template ensemble -----
    template_anchors = clip_classifier(args, classnames, template, clip_model)  # (d, n_cls)

    if args.use_vmf and args.paraphrase_json and os.path.exists(args.paraphrase_json):
        print(f"Loading paraphrases from {args.paraphrase_json}")
        paraphrases = load_paraphrases_json(args.paraphrase_json)
        # TODO(W3): wire build_vmf_text_anchors here once implemented
        clip_weights_text = template_anchors  # placeholder
        print("[INFO] vMF anchor not implemented yet (W3); using template ensemble.")
    else:
        clip_weights_text = template_anchors
        print("[INFO] using template ensemble text anchors (use_vmf=False or json missing)")

    # ----- 2x3 memory matrix -----
    cell_configs = build_default_cell_configs()
    matrix = MCP3DMemoryMatrix(num_classes=num_classes, cell_configs=cell_configs)
    print(matrix.summary())

    # ----- fusion weights (TODO W7: tune via A2 omega scan) -----
    fusion_weights = FusionWeights(
        zeta_text=1.0,
        zeta_cell={name: 1.0 for name in MCP3DMemoryMatrix.CELL_NAMES},
        zeta_residual=0.3,
        enable_residual=args.enable_residual,
    )

    # ----- running stats for z-score normalization -----
    running_stats = PerClassRunningStats(num_classes=num_classes)

    # ----- wandb logging -----
    if args.wandb:
        prefix = f"[mcp3d]/{args.lm3d}"
        if args.lm3d == "openshape":
            prefix += f"-{args.oshape_version}"
        elif args.lm3d == "ulip":
            prefix += f"-{args.ulip_version}"
        run_name = f"{prefix}/{dataset_name}/{args.cor_type if hasattr(args, 'cor_type') else 'clean'}"
        run = wandb.init(project="MCP-3D", config=cfg, name=run_name)

    # ----- run TTA -----
    acc = run_mcp3d(
        args=args,
        test_loader=test_loader,
        lm3d_model=lm3d_model,
        clip_weights_text=clip_weights_text,
        matrix=matrix,
        fusion_weights=fusion_weights,
        running_stats=running_stats,
    )

    if args.wandb:
        wandb.log({f"{dataset_name}": acc})
        run.finish()


if __name__ == "__main__":
    main()
