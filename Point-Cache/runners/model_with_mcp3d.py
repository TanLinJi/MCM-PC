@torch.no_grad()
def compute_vmf_anchor(
    paraphrase_features: torch.Tensor,  # (M, d), L2-normalized
    template_anchor: torch.Tensor,       # (d,), L2-normalized (multi-template ensemble)
    kappa0: float = DEFAULT_KAPPA0,
) -> torch.Tensor:
    """Closed-form MAP estimate of vMF mean direction with prior anchor.

    Posterior mode of vMF(z; mu, kappa) given prior vMF(mu; mu_0, kappa_0):
        a_c = normalize(kappa_hat * m_c + kappa_0 * z_bar)

    where m_c is the empirical mean direction of paraphrase embeddings,
    kappa_hat is estimated by Banerjee et al. method-of-moments,
    and z_bar = template_anchor (the prior).

    Args:
        paraphrase_features: (M, d) L2-normalized paraphrase embeddings
        template_anchor: (d,) prior anchor (multi-template ensemble), L2-normalized
        kappa0: prior concentration (higher -> trust template more)

    Returns:
        (d,) L2-normalized vMF MAP anchor.
    """
    M, d = paraphrase_features.shape

    # empirical mean direction
    sum_z = paraphrase_features.sum(dim=0)         # (d,)
    r_bar = sum_z.norm() / M                       # mean resultant length, scalar in [0, 1]
    m_c = sum_z / sum_z.norm()                     # (d,)

    # Banerjee et al. method-of-moments estimator for kappa_hat
    # kappa_hat = (r_bar * (d - r_bar^2)) / (1 - r_bar^2)
    eps = 1e-8
    kappa_hat = (r_bar * (d - r_bar ** 2)) / (1.0 - r_bar ** 2 + eps)
    kappa_hat = kappa_hat.clamp(min=eps)

    # MAP closed-form
    weighted = kappa_hat * m_c + kappa0 * template_anchor
    a_c = weighted / (weighted.norm() + eps)
    return a_c


