# Section 7: 2x3 Memory Matrix Manager
# ----------------------------------------------------------------------------
# Per plan section 3.5 (system architecture).
# Functional axis x Representation axis = 6 cells.
# Per audit Gap C1: A1 leave-one-out ablation will determine which 4-6 to keep.
# ============================================================================
class MCP3DMemoryMatrix:
    """Manages the 2x3 memory matrix for MCP-3D.

    Layout (functional x representation):

                    | global       | local
        ------------+--------------+--------------
        confidence  | global_conf  | local_conf
        compactness | global_comp  | local_comp
        boundary    | global_bnd   | local_bnd     # Gap C2: distinct from Point-Cache neg

    Each cell can be enabled/disabled via CellConfig.enabled for ablation A1.
    """

    CELL_NAMES = [
        "global_conf", "local_conf",
        "global_comp", "local_comp",
        "global_bnd", "local_bnd",
    ]

    def __init__(self, num_classes: int, cell_configs: Dict[str, CellConfig]):
        self.num_classes = num_classes
        # ensure all 6 names present (even if disabled)
        for name in self.CELL_NAMES:
            if name not in cell_configs:
                rep, func = name.split("_")
                cell_configs[name] = CellConfig(
                    name=name, representation=rep, function=func, enabled=False
                )
        self.cells: Dict[str, MemoryCell] = {
            name: MemoryCell(cfg) for name, cfg in cell_configs.items()
        }

    def get(self, name: str) -> MemoryCell:
        return self.cells[name]

    def all_filled(self) -> bool:
        return all(c.is_filled(self.num_classes) for c in self.cells.values() if c.cfg.enabled)

    def summary(self) -> str:
        lines = ["Memory matrix status:"]
        for name in self.CELL_NAMES:
            c = self.cells[name]
            lines.append(
                f"  {name:14s} | enabled={c.cfg.enabled} | classes={len(c.cache):3d} | items={c.num_items():4d}"
            )
        return "\n".join(lines)


