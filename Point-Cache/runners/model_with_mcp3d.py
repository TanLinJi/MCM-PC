# Section 5: Running Statistics (Streaming z-score)
# ----------------------------------------------------------------------------
# Per audit Gap A6: TTA is streaming with batch_size=1; we need running mean/std
# to z-score-normalize feature distance and ICP-CD distance before fusion.
# ============================================================================
class PerClassRunningStats:
    """Maintains exponentially-weighted running mean and std of a scalar per class.

    Used to z-score-normalize feature distance d_feat and geometric distance d_geo
    before linearly combining them with weight omega.
    """

    def __init__(
        self,
        num_classes: int,
        alpha: float = DEFAULT_ZSCORE_ALPHA,
        cold_start: int = DEFAULT_ICP_INIT_SAMPLES,
        device: str = "cuda",
    ):
        self.num_classes = num_classes
        self.alpha = alpha
        self.cold_start = cold_start
        self.device = device

        # per-class running statistics (cold-started with global pool)
        self.mu = torch.zeros(num_classes, device=device)
        self.var = torch.ones(num_classes, device=device)
        self.count = torch.zeros(num_classes, dtype=torch.long, device=device)

        # global pool for cold-start (used until per-class count reaches `cold_start`)
        self.global_mu = 0.0
        self.global_var = 1.0
        self.global_count = 0

    def update(self, class_idx: int, value: float) -> None:
        """Update running stats with a single observed value for class `class_idx`."""
        # global pool always updates
        self.global_count += 1
        delta = value - self.global_mu
        self.global_mu += delta / self.global_count
        self.global_var = (1 - self.alpha) * self.global_var + self.alpha * (delta ** 2)

        # per-class EMA update
        self.count[class_idx] += 1
        d = value - self.mu[class_idx].item()
        self.mu[class_idx] = (1 - self.alpha) * self.mu[class_idx] + self.alpha * value
        self.var[class_idx] = (1 - self.alpha) * self.var[class_idx] + self.alpha * (d ** 2)

    def normalize(self, class_idx: int, value: float) -> float:
        """Return z-scored value: (v - mu) / std."""
        eps = 1e-6
        if self.count[class_idx] < self.cold_start:
            mu = self.global_mu
            std = math.sqrt(self.global_var + eps)
        else:
            mu = self.mu[class_idx].item()
            std = math.sqrt(self.var[class_idx].item() + eps)
        return (value - mu) / std

    def state_dict(self) -> dict:
        return {
            "mu": self.mu.detach().cpu(),
            "var": self.var.detach().cpu(),
            "count": self.count.detach().cpu(),
            "global_mu": self.global_mu,
            "global_var": self.global_var,
            "global_count": self.global_count,
        }


